CREATE TABLE IF NOT EXISTS accounts (
    account_id VARCHAR(100) PRIMARY KEY,
    currency VARCHAR(3) NOT NULL,
    balance DECIMAL(19,2) NOT NULL DEFAULT 0 CHECK (balance >= 0),
    next_sequence BIGINT NOT NULL DEFAULT 1 CHECK (next_sequence > 0)
);

CREATE TABLE IF NOT EXISTS transactions (
    transaction_id VARCHAR(100) PRIMARY KEY,
    account_id VARCHAR(100) NOT NULL REFERENCES accounts(account_id),
    transaction_type VARCHAR(6) NOT NULL CHECK (transaction_type IN ('CREDIT', 'DEBIT')),
    amount DECIMAL(19,2) NOT NULL CHECK (amount > 0),
    currency VARCHAR(3) NOT NULL,
    sequence_number BIGINT NOT NULL CHECK (sequence_number > 0),
    state VARCHAR(10) NOT NULL CHECK (state IN ('PENDING', 'RETRY', 'PROCESSED', 'FAILED')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt_at BIGINT NOT NULL DEFAULT 0,
    last_error VARCHAR(500),
    UNIQUE (account_id, sequence_number)
);

CREATE TABLE IF NOT EXISTS deliveries (
    request_id VARCHAR(100) PRIMARY KEY,
    payload VARCHAR(1000) NOT NULL,
    transaction_id VARCHAR(100) NOT NULL,
    outcome VARCHAR(32) NOT NULL
);

CREATE TABLE IF NOT EXISTS ledger (
    transaction_id VARCHAR(100) PRIMARY KEY REFERENCES transactions(transaction_id),
    account_id VARCHAR(100) NOT NULL REFERENCES accounts(account_id),
    delta DECIMAL(19,2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    sequence_number BIGINT NOT NULL,
    UNIQUE (account_id, sequence_number)
);

CREATE TABLE IF NOT EXISTS rejected_inputs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(1000) NOT NULL,
    line_number BIGINT NOT NULL,
    reason VARCHAR(500) NOT NULL
);
